/**
 * Side-view car artwork for `SideCar`, keyed by Jolpica `constructorId`.
 *
 * Each car is our own vector drawing made over a free-licensed 2026 photo:
 * the outline is taken from the photo's cut-out, and the livery panels, wheels,
 * halo and highlights are drawn by hand on a measured grid. Every sponsor and
 * team logo is left off. Coordinates are in a nose-right drawing `width` ×
 * `height` px, with the ground at `ground`.
 */

export type Circle = { x: number; y: number; r: number };

export type CarArt = {
  /** Reviewed against the photo and shown on the team page; drafts only appear in /design. */
  ready: boolean;
  /** The photo the drawing was made from; CC BY requires this credit. */
  credit: { author: string; licence: string; url: string };
  width: number;
  height: number;
  ground: number;
  /** The whole car's silhouette, including the far-side wheels showing above the body. */
  outline: string;
  /** Dark bodywork: floor, sidepods, suspension and wings not in livery colour. */
  base: string;
  /**
   * The part of the drawing the silhouette may fill: cuts away the ground and
   * shadow the photo cut-out kept under the floor between the wheels. Defaults
   * to `groundCut`.
   */
  floorCut?: string;
  /** Livery colour panels over the base. */
  panels: { d: string; fill: string; opacity?: number }[];
  /** Panels outboard of the near-side wheels (front wing endplate), drawn over them. */
  foreground: { d: string; fill: string; opacity?: number }[];
  /**
   * Tonal shapes that give the dark bodywork depth: soft shadows under the
   * sidepod, lit edges, and suspension arms drawn in carbon with a lit edge.
   */
  shading: { d: string; kind: "shadow" | "light" | "arm" }[];
  /** Near-side wheels, rear first. */
  wheels: [Circle, Circle];
  /** Tyre compound on the photo, shown as the sidewall band. */
  compound: "soft" | "medium" | "hard";
  /** Wheel cover colour when it is part of the livery; dark otherwise. */
  wheelCover?: string;
  /** Far-side wheels, partly hidden behind the body. */
  farWheels: Circle[];
  cockpit: {
    /** Where the driver's helmet sits: top-left corner and width. */
    helmet: { x: number; y: number; width: number };
    /** Cockpit rim drawn in front of the helmet's lower edge. */
    side: string;
    halo: string;
    /** Halo colour when it is painted; the base colour otherwise. */
    haloColor?: string;
    mirror: string;
  };
  /**
   * Light catching top edges, drawn as soft strokes. The first must be the top
   * line of the chassis and nose, from the cockpit to the tip: the far-side
   * wheels are only drawn above it.
   */
  highlights: string[];
  /** Dark detail lines: wing slots, panel gaps. */
  details: string[];
  /** FIA rear rain light. */
  rainLight: string;
};

