/**
 * The drawing's area above the ground: clips away anything below the line
 * joining the two tyre contact points, and the ground behind the rear wheel
 * below its axle, where photo cut-outs keep shadows and track lines.
 */
export function groundCut(art: CarArt): string {
  const [rear, front] = art.wheels;
  const lip = 4;
  return (
    `M0 0 H${art.width} V${front.y + front.r + lip} L${front.x} ${front.y + front.r + lip} ` +
    `L${rear.x} ${rear.y + rear.r + lip} L${rear.x - rear.r} ${rear.y} L0 ${rear.y} Z`
  );
}

/** The rear wheel centre as shares of the drawing, for lining up tyre marks. */
export function rearWheelShare(art: CarArt): { x: number; y: number } {
  const [rear] = art.wheels;
  return { x: rear.x / art.width, y: (rear.y + rear.r) / art.height };
}
